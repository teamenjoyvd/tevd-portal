import { describe, expect, it } from 'vitest'

/**
 * Pins what scripts/check-ai-attribution.js treats as attribution, and — just
 * as important — what it must let through: this repo's own file is called
 * CLAUDE.md, so a check that matched the bare word would fail every commit
 * that touches it.
 */

import { findAttribution } from './check-ai-attribution'

describe('findAttribution — flags', () => {
  it.each([
    ['Claude co-author trailer', 'Fix thing\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'],
    ['lower-case trailer', 'fix\n\nco-authored-by: claude <x@y.z>'],
    ['Copilot trailer', 'fix\n\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>'],
    ['Generated-with footer', '## Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'],
    ['Generated-by AI line', 'This PR was generated by AI.'],
    ['bare noreply address', 'Signed: noreply@anthropic.com'],
  ])('%s', (_label, text) => {
    expect(findAttribution(text).length).toBeGreaterThan(0)
  })
})

describe('findAttribution — lets through', () => {
  it.each([
    ['the repo rules file', '[2611-DEV-1] Update CLAUDE.md working rules'],
    ['a human co-author', 'fix\n\nCo-Authored-By: Jane Doe <jane@example.com>'],
    ['a tool named in prose', 'Remove the Copilot config and the cursor-pointer style'],
    ['generated code mention', 'Regenerate types generated by supabase gen'],
    ['empty input', ''],
    ['missing input', undefined],
  ])('%s', (_label, text) => {
    expect(findAttribution(text)).toEqual([])
  })
})
